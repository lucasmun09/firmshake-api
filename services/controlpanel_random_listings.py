def random_price(min_price: float, max_price: float) -> float:
    low = min(min_price, max_price)
    high = max(min_price, max_price)
    if high <= low:
        return round(max(low, 0.0), 2)
    return round(random.uniform(low, high), 2)


def random_point_within_radius_miles(
    center_lat: float,
    center_lng: float,
    radius_miles: float,
) -> tuple[float, float]:
    """Uniform random point inside a circle (miles)."""
    if radius_miles <= 0:
        return center_lat, center_lng

    distance = radius_miles * math.sqrt(random.random())
    bearing = random.random() * 2 * math.pi

    lat1 = math.radians(center_lat)
    lng1 = math.radians(center_lng)
    angular_distance = distance / EARTH_RADIUS_MILES

    lat2 = math.asin(
        math.sin(lat1) * math.cos(angular_distance)
        + math.cos(lat1) * math.sin(angular_distance) * math.cos(bearing)
    )
    lng2 = lng1 + math.atan2(
        math.sin(bearing) * math.sin(angular_distance) * math.cos(lat1),
        math.cos(angular_distance) - math.sin(lat1) * math.sin(lat2),
    )
    return math.degrees(lat2), math.degrees(lng2)
